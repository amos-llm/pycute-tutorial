from pycute import composition, Layout

# 练习 1: hdim96: K (n=64, d=96) 按 (n,d) 存 -> sK = (64,96):(96,1)
# 转置视图 = (d,n) 行主序 "读法" (96,64):(64,1)
sK = Layout((64, 96), (96, 1))
Kt = composition(sK, Layout((96, 64), (64, 1)))
# = (96,64):(1,96)

# 练习 2: 通用转置 (M,N):(N,1) -> 转置视图 (N,M):
# 注意: 行主序的转置视图是列主序! 结果是 (5,8):(1,5), 不是 (5,8):(8,1)。
M, N = 8, 5
s = Layout((M, N), (N, 1))
st = composition(s, Layout((N, M), (M, 1)))
# = (5,8):(1,5)

